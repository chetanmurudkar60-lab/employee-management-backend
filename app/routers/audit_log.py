@router.get("/export/docx")
def export_audit_logs_docx(
    search: str | None = Query(None),
    db: Session = Depends(get_db),
    current_user: User = Depends(
        require_role(["Admin"])
    )
):
    # ================= QUERY =================

    query = (
        db.query(AuditLog)
        .order_by(AuditLog.created_at.desc())
    )

    # ================= SEARCH =================

    if search:
        search_value = f"%{search.strip()}%"

        query = query.filter(
            AuditLog.user_name.ilike(search_value)
            | AuditLog.action.ilike(search_value)
            | AuditLog.description.ilike(search_value)
        )

    audit_logs = query.all()

    # ================= CREATE DOCUMENT =================

    document = Document()

    # Title

    title = document.add_heading(
        "Audit Logs",
        level=0
    )

    # Description

    document.add_paragraph(
        "Employee Management System"
    )

    document.add_paragraph(
        f"Generated by: {current_user.name}"
    )

    document.add_paragraph(
        f"Total activities: {len(audit_logs)}"
    )

    # ================= TABLE =================

    table = document.add_table(
        rows=1,
        cols=6
    )

    table.style = "Table Grid"

    header_cells = table.rows[0].cells

    header_cells[0].text = "User"
    header_cells[1].text = "Role"
    header_cells[2].text = "Action"
    header_cells[3].text = "Details"
    header_cells[4].text = "Target"
    header_cells[5].text = "Date & Time"

    # ================= TABLE DATA =================

    for log in audit_logs:

        row_cells = table.add_row().cells

        row_cells[0].text = log.user_name or "Unknown"
        row_cells[1].text = log.role or "—"
        row_cells[2].text = log.action or "—"
        row_cells[3].text = log.description or "—"

        if log.target_type:

            if log.target_id is not None:
                target = f"{log.target_type} #{log.target_id}"
            else:
                target = log.target_type

        else:
            target = "—"

        row_cells[4].text = target

        if log.created_at:
            row_cells[5].text = log.created_at.strftime(
                "%d %b %Y, %I:%M %p"
            )
        else:
            row_cells[5].text = "—"

    # ================= SAVE TO MEMORY =================

    file_stream = BytesIO()

    document.save(file_stream)

    file_stream.seek(0)

    # ================= DOWNLOAD =================

    return StreamingResponse(
        file_stream,
        media_type=(
            "application/vnd.openxmlformats-officedocument."
            "wordprocessingml.document"
        ),
        headers={
            "Content-Disposition": (
                'attachment; filename="audit_logs.docx"'
            )
        }
    )
    
    
